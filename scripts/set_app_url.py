#!/usr/bin/env python3
"""
ReviewLens PWA Target URL Updater.
Validates that the provided URL uses HTTPS and updates pwa/config.js.
Usage:
    python scripts/set_app_url.py https://my-reviewlens.streamlit.app
"""

import sys
from pathlib import Path
import urllib.parse

CONFIG_PATH = Path(__file__).resolve().parent.parent / "pwa" / "config.js"


def validate_and_format_url(raw_url: str) -> str:
    """
    Validates that the URL uses HTTPS and has a valid domain.
    Raises ValueError on invalid syntax or non-HTTPS schemes.
    """
    if not raw_url or not isinstance(raw_url, str):
        raise ValueError("URL must be a non-empty string.")

    cleaned = raw_url.strip()
    parsed = urllib.parse.urlparse(cleaned)

    if parsed.scheme.lower() != "https":
        raise ValueError(f"PWA targets must enforce HTTPS (got scheme '{parsed.scheme}').")

    if not parsed.netloc:
        raise ValueError("URL must contain a valid domain name.")

    return cleaned


def set_app_url(url: str) -> None:
    """Updates pwa/config.js with the validated HTTPS URL."""
    valid_url = validate_and_format_url(url)
    CONFIG_PATH.parent.mkdir(parents=True, exist_ok=True)
    
    content = (
        "// ReviewLens Progressive Web App (PWA) Configuration\n"
        "// Automatically generated by scripts/set_app_url.py\n"
        f'const APP_URL = "{valid_url}";\n'
    )
    with open(CONFIG_PATH, "w", encoding="utf-8") as f:
        f.write(content)

    print(f"✅ Successfully updated {CONFIG_PATH.name} -> {valid_url}")


if __name__ == "__main__":
    if len(sys.argv) < 2:
        print("Usage: python scripts/set_app_url.py <https://url>")
        sys.exit(1)

    try:
        set_app_url(sys.argv[1])
    except ValueError as err:
        print(f"❌ Error: {err}")
        sys.exit(1)
